class Solution(object):
    def sampleStats(self, count):
        """
        :type count: List[int]
        :rtype: List[float]
        """
        # process
        # get minimum, maximum, and mode
        minmium, maximum, mode = -1, -1, 0
        total = 0
        total_count = 0
        mode_count = 0
        for idx, c in enumerate(count):
            total += c * idx
            total_count += c
            if c > mode_count:
                mode_count = c
                mode = idx
            if c > 0:
                if minmium == -1:
                    minmium = idx
                maximum = idx
        # print(minmium, maximum, mode)

        # get mean
        mean = (total * 1.0) / total_count
        # print(mean)

        # get median
        # helper function
        def getTarget(target):
            res = 0
            idx = 0
            c = 0
            while c < target:
                res = idx
                c += count[idx]
                idx += 1
            return res

        # print(getTarget(4))
        # print(getTarget(5))

        if total_count % 2 == 0:
            target = total_count // 2
            median = ((getTarget(target) + getTarget(target + 1)) * 1.0) / 2
        else:
            target = (total_count + 1) // 2
            median = getTarget(target)
        # print(median)

        return [minmium, maximum, mean, median, mode]


