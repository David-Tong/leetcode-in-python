class Solution(object):
    def stoneGameV(self, stoneValue):
        """
        :type stoneValue: List[int]
        :rtype: int
        """
        # pre-process
        L = len(stoneValue)

        # prefix sums
        presums = [0]
        for value in stoneValue:
            presums.append(presums[-1] + value)

        # dp[start][end] = best score for interval [start, end)
        dp = [[0] * (L + 1) for _ in range(L + 1)]

        # interval length from 2 to L
        for length in range(2, L + 1):  # interval size >= 2
            for start in range(0, L - length + 1):
                end = start + length
                best = 0

                # x goes from start+1 to end-1
                for x in range(start + 1, end):
                    left_total = presums[x] - presums[start]
                    right_total = presums[end] - presums[x]

                    if left_total <= right_total:
                        best = max(best, left_total + dp[start][x])
                    if left_total >= right_total:
                        best = max(best, right_total + dp[x][end])

                dp[start][end] = best

        ans = dp[0][L]
        return ans


